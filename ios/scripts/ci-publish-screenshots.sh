#!/bin/bash
# CI only. Publishes this run's Simulator screenshots to docs/screenshots/ios/ on the
# branch that triggered the run, as a bot commit that does not trigger CI again.
#
# Why commit them: the development sandbox cannot download Actions artifacts (the blob
# host is blocked there), and the README wants these images anyway. To keep the
# repository small the committed copies are JPEGs, 600 px wide; the full-size PNGs are in
# the run's `ios-screenshots` artifact.
#
# Needs: SHOTS (directory with *.png, optionally debug/*.txt and TEST-RESULTS.txt),
#        BRANCH, RUN_URL.
# Optional: WEB_SOURCE ("real" or "placeholder"), SIM_LABEL.
set -euo pipefail

main() {
  local src="${SHOTS:?SHOTS is required}"
  local branch="${BRANCH:?BRANCH is required}"
  local run_url="${RUN_URL:-}"
  local dest="docs/screenshots/ios"
  local stage
  stage="$(mktemp -d)"

  shopt -s nullglob
  local count=0
  local file
  local name
  for file in "$src"/*.png; do
    name="$(basename "$file" .png)"
    sips -s format jpeg -s formatOptions 82 --resampleWidth 600 "$file" --out "$stage/$name.jpg" > /dev/null
    count=$((count + 1))
  done
  if [ "$count" -eq 0 ]; then
    echo "publish: no screenshots were produced; nothing to publish"
    return 0
  fi
  if [ -d "$src/debug" ]; then
    mkdir -p "$stage/debug"
    for file in "$src"/debug/*.txt; do
      cp "$file" "$stage/debug/"
    done
  fi
  if [ -f "$src/TEST-RESULTS.txt" ]; then
    cp "$src/TEST-RESULTS.txt" "$stage/TEST-RESULTS.txt"
  fi

  # Compressed screen recordings are produced only on demand (see the workflow). When this
  # run has none, the ones already committed are kept.
  local have_recordings=0
  if [ -n "${RECORDINGS:-}" ] && [ -d "${RECORDINGS:-}" ]; then
    for file in "$RECORDINGS"/*.mp4; do
      cp "$file" "$stage/"
      have_recordings=1
    done
  fi

  {
    echo "# iOS Simulator screenshots"
    echo ""
    echo "Generated by the \`iOS\` workflow; do not edit by hand. Every run replaces this folder."
    echo ""
    echo "- Run: ${run_url:-unknown}"
    echo "- Simulator: ${SIM_LABEL:-unknown}"
    echo "- Story shown in the app: the **${WEB_SOURCE:-unknown}** web story"
    echo "- Test results and notes of that run: [TEST-RESULTS.txt](TEST-RESULTS.txt)"
    echo "- Screen recordings: every run uploads full-size ones as the \`ios-video\` artifact."
    echo "  Compressed copies (\`app-demo-story.mp4\`, the demo story in the app, and"
    echo "  \`messages-extension-3x.mp4\`, the walkthrough inside Messages at 3x speed) are"
    echo "  committed here only when a run is asked to, so they can be older than the images."
    echo ""
    echo "What the file names mean:"
    echo ""
    echo "| Prefix | What it is |"
    echo "|--------|------------|"
    echo "| \`app-\` | The containing app on the Simulator, captured by UI tests. |"
    echo "| \`simctl-\` | The containing app, launched and captured with \`xcrun simctl\`. |"
    echo "| \`gallery-\` | The extension's native views hosted in the app's debug gallery. **Not Messages.** |"
    echo "| \`render-\` | Offscreen renders from unit tests (share card, live bubble). **Not Messages.** |"
    echo "| \`messages-\` | The real Messages app in the Simulator (automation attempt; see the test results for how far it got). |"
    echo ""
    for file in "$stage"/*.jpg; do
      name="$(basename "$file")"
      echo "### ${name%.jpg}"
      echo ""
      echo "<img src=\"$name\" width=\"300\" alt=\"${name%.jpg}\">"
      echo ""
    done
  } > "$stage/README.md"

  git config user.name "github-actions[bot]"
  git config user.email "41898282+github-actions[bot]@users.noreply.github.com"

  local attempt
  for attempt in 1 2 3 4 5 6; do
    git fetch --quiet --depth 1 origin "$branch"
    git checkout --quiet --force --detach FETCH_HEAD
    local keep
    keep="$(mktemp -d)"
    if [ "$have_recordings" -eq 0 ] && [ -d "$dest" ]; then
      for file in "$dest"/*.mp4; do
        cp "$file" "$keep/"
      done
    fi
    rm -rf "$dest"
    mkdir -p "$dest"
    cp -R "$stage"/. "$dest"/
    for file in "$keep"/*.mp4; do
      cp "$file" "$dest/"
    done
    git add -A "$dest"
    if git diff --cached --quiet; then
      echo "publish: screenshots are unchanged"
      return 0
    fi
    git commit --quiet -m "Update iOS Simulator screenshots [skip ci]" -m "From ${run_url:-an iOS workflow run}."
    if git push --quiet origin "HEAD:refs/heads/$branch"; then
      echo "publish: pushed $count screenshots to $dest on $branch ($(git rev-parse --short HEAD))"
      return 0
    fi
    echo "publish: push was rejected (attempt $attempt); retrying on the new branch head"
    sleep $((attempt * 4))
  done
  echo "publish: giving up after repeated push rejections" >&2
  return 1
}

main "$@"
exit $?
