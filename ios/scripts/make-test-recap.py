#!/usr/bin/env python3
"""Write ios/Tests/UI/TestRecap.swift: an invented recap that is NOT the built-in sample.

The UI tests paste its link the way a person would paste their own recap link, so the
flows that only apply to a person's own recap (it is listed under "Your recaps", it can be
sent, it can be cleared) are exercised with something that is not labelled "Sample".

Everything in it is made up. It starts from the shape of the shared test vector
(tests/vectors/payload-v1.json) so that every slide of the story has data, then replaces
the chat, the people, the quotes and the numbers.
"""
import base64
import json
import os
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
VECTOR = os.path.join(REPO, "tests", "vectors", "payload-v1.json")
SWIFT = os.path.join(REPO, "ios", "Tests", "UI", "TestRecap.swift")

NAMES = {
    "Maya": "Noor",
    "Dev": "Eli",
    "Priya": "Kira",
    "Jonah": "Tomas",
    "Tess": "Wren",
    "Marcus": "Ansel",
    "Lena": "Bea",
}
QUOTES = [
    "“Easy loop, two hours tops” was five hours ago and we can still see the car park",
    "Who packed eleven bananas and zero water",
    "SUMMIT!!! (it was the wrong summit)",
]
SCALE = 0.27


def scale(value):
    """Shrinks every count so the totals differ from the sample's."""
    if isinstance(value, dict):
        return {key: (item if key in ("v", "members", "peak_hour") else scale(item)) for key, item in value.items()}
    if isinstance(value, list):
        return [scale(item) for item in value]
    if isinstance(value, bool):
        return value
    if isinstance(value, int) and value > 50:
        return int(round(value * SCALE))
    return value


def rename(value):
    if isinstance(value, dict):
        return {key: rename(item) for key, item in value.items()}
    if isinstance(value, list):
        return [rename(item) for item in value]
    if isinstance(value, str):
        return NAMES.get(value, value)
    return value


def count(number):
    return "{:,}".format(number)


def main():
    with open(VECTOR, encoding="utf-8") as f:
        stats = json.load(f)["stats"]

    stats = rename(scale(stats))
    stats["chat"] = {"name": "Sunday Hikers 🥾", "members": 7}
    stats["meta"] = {"generator": "ios-ui-tests", "source": "invented", "generated": "2026-11-11"}
    for entry, quote in zip(stats.get("most_reacted", []), QUOTES):
        entry["text"] = quote

    senders = {sender["name"]: sender for sender in stats["senders"]}
    details = {
        "yapper": "%s messages. Nobody asked." % count(senders["Noor"]["messages"]),
        "lurker": "%s messages. Reads everything, says little." % count(senders["Bea"]["messages"]),
        "night_owl": "%s messages after midnight." % count(senders["Eli"]["late_night"]),
        "comedian": "Made the chat laugh 246 times.",
        "hype": "Handed out %s tapbacks." % count(senders["Wren"]["reactions_given"]),
        "novelist": "10.0 words per message. A paragraph person.",
    }
    for award in stats.get("awards", []):
        if award.get("id") in details:
            award["detail"] = details[award["id"]]

    text = json.dumps(stats, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    raw = packer.compress(text.encode("utf-8")) + packer.flush()
    payload = base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")

    # Round trip, the way every reader of the link does it.
    padded = payload + "=" * (-len(payload) % 4)
    again = json.loads(zlib.decompress(base64.urlsafe_b64decode(padded), -15).decode("utf-8"))
    assert again == stats

    chunks = [payload[i:i + 96] for i in range(0, len(payload), 96)]
    literal = ",\n".join('        "%s"' % chunk for chunk in chunks)
    source = (
        "import Foundation\n"
        "\n"
        "/// An invented recap that is not the built-in sample (made-up chat, people and numbers).\n"
        "/// UI tests paste its link the way a person pastes their own recap link.\n"
        "/// Generated by `python3 ios/scripts/make-test-recap.py`; do not edit by hand.\n"
        "enum TestRecap {\n"
        "    static let chatName = \"%s\"\n"
        "    /// `totals.messages`, formatted the way the app shows it.\n"
        "    static let formattedTotal = \"%s\"\n"
        "    static let slideCount = 12\n"
        "\n"
        "    static let payload: String = [\n"
        "%s\n"
        "    ].joined()\n"
        "\n"
        "    /// The https story link, as the recap maker hands it out.\n"
        "    static let link = \"https://averyhsu.github.io/imessage-wrap/#w1=\" + payload\n"
        "}\n"
    ) % ("Sunday Hikers", count(stats["totals"]["messages"]), literal)
    with open(SWIFT, "w", encoding="utf-8") as f:
        f.write(source)
    print("TestRecap.swift written: %d-character payload, %s messages" % (len(payload), count(stats["totals"]["messages"])))


if __name__ == "__main__":
    main()
